import type { Message, StopReason, SystemBlock, ToolResultBlock } from "./provider.ts";
import type { SkillManifest } from "./skills.ts";

// ---------------------------------------------------------------------------
// Memory
// ---------------------------------------------------------------------------

export type TrimMode = "turns" | "tokens";

export interface TrimPolicy {
  mode: TrimMode;
  /** Number of turns to keep, or token budget threshold. */
  keep: number;
}

export interface TrimSummary {
  /** Number of messages removed from the head of the history. */
  removedCount: number;
  /** Token estimate of the removed messages (via provider.countTokens). */
  removedTokens: number;
  /**
   * A serialized representation of the removed messages, suitable to feed the
   * summarizer. Format is stable for tests: each removed message rendered as
   * `"<role>: <text-or-json>"` joined by "\n". Never includes the kept tail.
   */
  archivedText: string;
}

/**
 * Stable identifier for a resumable session.
 *
 * roxy-agent is a coding agent (Claude-Code / Codex style), NOT a server. A
 * single process may hold several sessions over its lifetime. A session is the
 * unit that survives a process exit: its history is persisted as an append-only
 * rollout, keyed by this id, so the user can resume the exact context on the
 * next run (`--resume <sessionId>`). Isolation granularity is the {@link Agent}
 * INSTANCE — one Agent per sessionId, each carrying its own memory partition —
 * NOT a thread or a remote TCP session.
 *
 * Persistence is APPEND-ONLY rollout files (Codex style: one JSONL event
 * stream per session): rolling JSONL needs no schema migration as the message
 * envelope evolves, and replay rebuilds memory trivially.
 *
 * Generated by the framework when omitted; stable across resume.
 */
export type SessionId = string;

// ---------------------------------------------------------------------------
// Rollout (session persistence — the durable truth a session resumes from)
// ---------------------------------------------------------------------------

/**
 * A single append-only event in a session's rollout. This is the MINIMAL
 * stream sufficient to REPLAY a session back into memory — NOT the same as a
 * {@link TrajectoryEvent} (which is coarse observability for debugging and is
 * not required to rebuild state). Only what's needed to reconstruct the
 * conversation: the user input, each assistant turn (with its tool_use
 * blocks), each tool result, and HITL decisions.
 */
export type RolloutEvent =
  | { type: "session_start"; sessionId: SessionId; createdAt: number }
  | { type: "user_input"; message: Message }
  | { type: "assistant_turn"; message: Message; stopReason: StopReason }
  | { type: "tool_result"; result: ToolResultBlock }
  | { type: "hitl_decision"; traceId: string; approved: boolean }
  | { type: "compaction"; summary: string; compactedCount: number; ts: number }
  /**
   * Link from a parent session to an isolated subagent session it spawned via
   * the `task` tool. Recorded once per subagent name in the PARENT rollout so
   * a UI/audit can jump from a delegation to the child's own rollout
   * (`<childSessionId>.rollout.jsonl`). Ignored on replay — it does not
   * reconstruct any parent message.
   */
  | { type: "subagent_delegated"; childSessionId: SessionId; name: string; ts: number };

/**
 * Append-only, replay-only session store. One rollout file per session (e.g.
 * `~/.roxy/sessions/<sessionId>.rollout.jsonl`).
 *
 * - `append` is the ONLY write — events go in order, never mutated.
 * - `replay` is the inverse of the live loop: re-feeds the rollout into an
 *   {@link IMemoryProvider} so a resumed session's history is identical to the
 *   original. This is what `AgentRuntime.create({ sessionId })` calls before the first
 *   `invoke()`.
 * - `list` + `meta` back the `--resume` picker UI.
 *
 * Implementations are trivial over JSONL — no schema, no migrations. A field
 * added to {@link Message} or {@link RolloutEvent} just means older replays
 * ignore it; nothing breaks.
 */
export interface ISessionStore {
  /** Append one event to the session's rollout. Must not block the loop long. */
  append(sessionId: SessionId, event: RolloutEvent): Promise<void>;
  /** Read a session's full rollout, oldest-first. Empty if unknown. */
  read(sessionId: SessionId): Promise<RolloutEvent[]>;
  /** List resumable sessions (newest-first) for the resume picker. */
  list(): Promise<SessionMeta[]>;
  /** Lightweight metadata for a session without reading the whole rollout. */
  meta(sessionId: SessionId): Promise<SessionMeta | null>;
}

/** Summary of a stored session, for listing/resume UI. */
export interface SessionMeta {
  sessionId: SessionId;
  createdAt: number;
  /** Timestamp of the last appended event. */
  updatedAt: number;
  /** Count of events in the rollout. */
  eventCount: number;
}

export interface IMemoryProvider {
  /** Append a message to the given session's history. */
  append(sessionId: SessionId, msg: Message): Promise<void>;
  /** Full history of the given session, oldest-first. */
  getAll(sessionId: SessionId): Promise<Message[]>;
  /** Last `count` messages of the given session, oldest-first. */
  getSince(sessionId: SessionId, count: number): Promise<Message[]>;
  /**
   * Remove messages from the HEAD of the given session's stored history until
   * the policy is satisfied (keep the latest N turns, or stay under a token
   * budget). Always preserves the most recent user message. Returns what was
   * removed.
   */
  trim(sessionId: SessionId, policy: TrimPolicy): Promise<TrimSummary>;
  setSummary(sessionId: SessionId, summary: string): Promise<void>;
  getSummary(sessionId: SessionId): Promise<string | null>;
  /**
   * Insert a message at the FRONT of the session's history (before all
   * existing messages). Used to inject a summarization message after trim.
   */
  prependMessage(sessionId: SessionId, msg: Message): Promise<void>;
  /** Drop the given session's history and summary (e.g. /clear). */
  clear(sessionId: SessionId): Promise<void>;
}

/** Sliding-window trimmer using a token or turn policy. */
export interface Trimmer {
  trim(
    messages: Message[],
    policy: TrimPolicy,
  ): {
    kept: Message[];
    summary: TrimSummary;
  };
}

/** Async background summarizer of trimmed history. */
export interface Summarizer {
  /**
   * Produce a prose summary of the archived text. On failure the summarizer
   * logs a warning and resolves with the empty string (NOT a rejection) — the
   * runtime then simply omits the summary block rather than crashing the turn.
   */
  summarize(archivedText: string): Promise<string>;
}

/**
 * System-prompt assembly contract (implemented in the memory module). Composes
 * the top-level system prompt as an ordered ARRAY of {@link SystemBlock}s —
 * NOT a concatenated string — so each segment can carry its own
 * `cache_control` breakpoint.
 *
 * Segment order is most-stable-first (for cache hit rate):
 *   1. archived-summary block — only when `summary` is non-empty (changes on
 *      trim; placed first so it does not push the stable base out of cache)
 *   2. base block — the `config.system.systemPrompt` (turn-invariant)
 *   3. skill-catalog block — bounded XML rendered from `skills` metadata only.
 *      Implicitly selected bodies load via `read_file`; explicitly selected
 *      bodies are transient user-role `<skill>` messages for that turn.
 *
 * A null/empty summary yields no summary block. An empty skills list yields no
 * skill-catalog block. Exposed here as a type so the runtime depends on the
 * contract, not the impl.
 */
export type SystemPromptBuilder = (
  base: string,
  summary: string | null,
  skills: SkillManifest[],
  skillCatalogMaxChars?: number,
) => SystemBlock[];
